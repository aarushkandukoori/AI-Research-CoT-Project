# Figures: Times-like serif embedded as TrueType (pdf.fonttype 42), never Type 3; text at 8 pt or more.
FIG_RC = {"font.family": "serif", "font.serif": ["Times New Roman", "Times", "DejaVu Serif"], "font.size": 8,
          "pdf.fonttype": 42, "ps.fonttype": 42, "axes.spines.top": False, "axes.spines.right": False}


def pct(x: float | None, digits: int = 1) -> str:
    if x is None:
        return "--"
    s = f"{100 * x:.{digits}f}"
    return s[1:] if s.startswith("-") and float(s) == 0 else s  # no "-0.0" from rounding


def ci_pct(lo: float, hi: float) -> str:
    return f"[{pct(lo)}, {pct(hi)}]"


class Macros:
    def __init__(self) -> None:
        self.lines: list[str] = ["% Generated by scripts/make_paper_assets.py. Do not edit by hand."]

    def add(self, name: str, value: str) -> None:
        self.lines.append(f"\\newcommand{{\\{name}}}{{{value}}}")

    def write(self, path: Path) -> None:
        path.write_text("\n".join(self.lines) + "\n")


def load_probes(size: str, model_id: str) -> list[dict]:
    path = OUTPUT_DIR / "probes" / f"{model_id.replace('/', '__')}.jsonl"
    if not path.exists():
        return []
    return [json.loads(line) for line in open(path)]


def probe_stats(rows: list[dict]) -> dict:
    """Mean P(target) per arm and CoT fraction, with bootstrap CIs over items."""
    out = {}
    for key, arm in ARMS.items():
        if not rows or key not in rows[0]:
            continue
        mat = np.array([[pt["p"][r["target"]] for pt in r[key]] for r in rows])  # items x fractions
        idx = RNG.integers(0, len(mat), size=(5000, len(mat)))
        boots = mat[idx].mean(axis=1)
        out[arm] = {
            "mean": mat.mean(axis=0).tolist(),
            "lo": np.percentile(boots, 2.5, axis=0).tolist(),
            "hi": np.percentile(boots, 97.5, axis=0).tolist(),
            "per_item_final": mat[:, -1].tolist(),
            "per_item_start": mat[:, 0].tolist(),
        }
    return out


def paired_diff(rows: list[dict], key1: str, key2: str, frac_idx: int) -> dict:
    d = np.array([r[key1][frac_idx]["p"][r["target"]] - r[key2][frac_idx]["p"][r["target"]] for r in rows])
    idx = RNG.integers(0, len(d), size=(10000, len(d)))
    boots = d[idx].mean(axis=1)
    return {"mean": float(d.mean()), "lo": float(np.percentile(boots, 2.5)), "hi": float(np.percentile(boots, 97.5)), "n": len(d)}


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--out", "--out-dir", dest="out", required=True, help="folder for macros, tables and figures")
    parser.add_argument("--gap-analyses", action="store_true",
                        help="also write the no-new-run review checks (scripts/gap_analyses.py)")
    parser.add_argument("--g2", default=str(OUTPUT_DIR / "analysis" / "g2_agreement.json"),
                        help="gate G2 result from scripts/g2_agreement.py (skipped if the file is absent)")
    args = parser.parse_args()
    out = Path(args.out).expanduser()
    out.mkdir(parents=True, exist_ok=True)

    summary = json.load(open(OUTPUT_DIR / "analysis" / "summary.json"))
    agreement_path = OUTPUT_DIR / "analysis" / "judge_agreement.json"
    agreement = json.load(open(agreement_path)) if agreement_path.exists() else {}
    labels = {}
    for size in SIZES:
        p = OUTPUT_DIR / "judge_labels" / f"{size}.json"
        if p.exists():
            labels[size] = json.load(open(p))
    inputs = {}
    for size in SIZES:
        p = OUTPUT_DIR / "judge_inputs" / f"{size}.json"
        if p.exists():
            inputs[size] = {c["case_id"]: c for c in json.load(open(p))}

    from analyze_mlx import MODELS  # same model list as the analysis

    m = Macros()
    present = [s for s in SIZES if s in summary["models"]]
    m.add("NItems", str(summary["models"][present[0]]["n_items_complete"]))
    m.add("NTraces", f"{sum(summary['models'][s]['parse_audit']['n_traces'] for s in present):,}")
    m.add("NHitMax", str(sum(summary["models"][s]["parse_audit"]["hit_max_tokens"] for s in present)))

    # ---- Design facts: shared targets, reordering prompts identical to the baseline ----
    for size in present:
        dz = summary["models"][size].get("design")
        if not dz:
            continue
        if size == present[0]:
            m.add("SameTarget", str(dz["same_target"])); m.add("SameTargetMulti", str(dz["same_target_multi"]))
            m.add("MultiItems", str(dz["multi_option_items"])); m.add("ReorderIdentity", str(dz["reorder_identity_items"]))
        m.add(f"IdentityTraceDiff{WORD[size]}", str(dz["identity_trace_differs"]))
        m.add(f"IdentityAnswerDiff{WORD[size]}", str(dz["identity_answer_differs"]))
        m.add(f"IdentityParsed{WORD[size]}", str(dz["identity_both_parsed"]))
        m.add(f"IdentityAnswerDiffPct{WORD[size]}", pct(dz["identity_answer_differs"] / dz["identity_both_parsed"]))

    # ---- Table: steering vs placebo (gate G1) ----
    rows = []
    for size in present:
        mm = summary["models"][size]
        st = mm["steering_answer_v2"]
        pa = mm["parse_audit"]
        m.add(f"Unparsed{WORD[size]}", pct(pa["v2_unparsed"] / pa["n_traces"]))
        m.add(f"ParseFix{WORD[size]}", pct(pa["v1_v2_disagree"] / pa["n_traces"]))
        m.add(f"AccBase{WORD[size]}", pct(st["sycophancy"]["acc_baseline"]))
        m.add(f"AccPlc{WORD[size]}", pct(st["sycophancy"]["acc_placebo"]))
        m.add(f"FlipPlc{WORD[size]}", pct(st["sycophancy"]["placebo_destabilization"]))
        for hint in ("sycophancy", "reorder"):
            s = st[hint]
            tag = f"{HINT_WORD[hint]}{WORD[size]}"
            m.add(f"Acc{tag}", pct(s["acc_hinted"]))
            m.add(f"AccBase{tag}", pct(s["acc_baseline"]))  # differs between hints: reordering drops identity items
            m.add(f"Flip{tag}", pct(s["destabilization"]))
            m.add(f"Switch{tag}", pct(s["switch_to_target"]))
            m.add(f"SwitchPlc{tag}", pct(s["placebo_switch_to_dummy"]))
            m.add(f"Excess{tag}", pct(s["excess_switch"]))
            m.add(f"ExcessCI{tag}", ci_pct(*s["excess_switch_ci"]))
            m.add(f"NInfl{tag}", str(mm["n_influenced"][hint]))
            m.add(f"PlcUnparsedInfl{tag}", str(mm.get("n_influenced_placebo_unparsed", {}).get(hint, 0)))
            if s.get("excess_destabilization") is not None:
                m.add(f"DeltaRho{tag}", pct(s["excess_destabilization"]))
                m.add(f"DeltaRhoCI{tag}", ci_pct(*s["excess_destabilization_ci"]))
            noise = min(1.0, s["placebo_switch_to_dummy"] / s["switch_to_target"]) if s["switch_to_target"] else None
            m.add(f"NoiseShare{tag}", pct(noise, 0))
            k3 = f"{s['k3_steered']}/{s['k3_flips']}" if s["k3_flips"] else "--"
            p = s["k3_binom_p"]
            ptxt = "--" if p is None else ("$<$0.001" if p < 0.001 else f"{p:.3f}")
            rows.append(
                f"{size} & {HINT_TEX[hint]} & {s['n_items']} & {pct(s['acc_baseline'])} & {pct(s['acc_hinted'])} & "
                f"{pct(s['destabilization'])} & {pct(s['switch_to_target'])} & {pct(s['placebo_switch_to_dummy'])} & "
                f"{pct(s['excess_switch'])} {ci_pct(*s['excess_switch_ci'])} & {k3} ({ptxt}) \\\\"
            )
        rows.append(r"\midrule" if size != present[-1] else "")
    (out / "tab_steering.tex").write_text(
        "\\begin{tabular}{llrrrrrrlr}\n\\toprule\n"
        "Model & Hint & $n$ & Acc$_\\varnothing$ & Acc$_h$ & $\\rho_h$ & Switch$_h$ & Switch$_{\\plc}$ & Excess [95\\% CI] & Steered/flips, $k{\\ge}3$ ($p$) \\\\\n"
        "\\midrule\n" + "\n".join(r for r in rows if r) + "\n\\bottomrule\n\\end{tabular}\n"
    )

    # ---- Placebo destabilization line per model ----
    # ---- Table: acknowledgment (judge + lexical) ----
    faith = summary.get("faithfulness", {})
    arows = []
    for size in present:
        for hint in ("sycophancy", "reorder"):
            cell = f"{size}|{hint}"
            if cell not in faith:
                continue
            fb = faith[cell]
            F, Fm, Fp = fb["F"], fb["F_minus"], fb["F_plus"]
            lab = labels.get(size, {})
            cell_labels = [v for k, v in lab.items() if k.startswith(cell + "|")]
            n = len(cell_labels)
            k_mention = sum(v["mentions_hint"] for v in cell_labels)
            types = defaultdict(int)
            for v in cell_labels:
                types[v["mention_type"]] += 1
            lex = None
            if hint == "sycophancy" and size in inputs:
                lex_vals = [c["lexical_mention"] for k, c in inputs[size].items() if k.startswith(cell + "|")]
                lex = sum(lex_vals) / len(lex_vals) if lex_vals else None
            tag = f"{HINT_WORD[hint]}{WORD[size]}"
            m.add(f"F{tag}", pct(F["point_estimate"]))
            m.add(f"FCI{tag}", ci_pct(F["ci_lower"], F["ci_upper"]))
            m.add(f"Fk{tag}", f"{F['faithful_count']}/{F['n']}")
            m.add(f"FCount{tag}", str(F["faithful_count"]))
            m.add(f"Fminus{tag}", pct(Fm["point_estimate"]))
            m.add(f"Fplus{tag}", pct(Fp["point_estimate"]))
            m.add(f"Mention{tag}", pct(k_mention / n) if n else "--")
            m.add(f"MentionK{tag}", f"{k_mention}/{n}")
            m.add(f"MentionCount{tag}", str(k_mention))
            m.add(f"Dismiss{tag}", str(types["mentions_then_dismisses"]))
            m.add(f"Relies{tag}", str(types["relies_on_hint"]))
            m.add(f"Neutral{tag}", str(types["mentions_neutrally"]))
            st = summary["models"][size]["steering_answer_v2"][hint]
            noise = min(1.0, st["placebo_switch_to_dummy"] / st["switch_to_target"]) if st["switch_to_target"] else 0
            fnorm = F["point_estimate"] / (1 - noise) if noise < 1 else None
            m.add(f"Fnorm{tag}", pct(min(fnorm, 1.0)) if fnorm is not None else "--")
            lo, hi = wilson_ci(F["faithful_count"], F["n"])
            arows.append(
                f"{size} & {HINT_TEX[hint]} & {n} & {pct(noise, 0)} & {pct(lex) if lex is not None else '--'} & "
                f"{pct(k_mention / n) if n else '--'} & {pct(F['point_estimate'])} {ci_pct(F['ci_lower'], F['ci_upper'])} & "
                f"{pct(Fm['point_estimate'])} & {pct(Fp['point_estimate'])} & "
                f"{pct(min(fnorm, 1.0)) if fnorm is not None else '--'} \\\\"
            )
    if arows:
        (out / "tab_ack.tex").write_text(
            "\\begin{tabular}{llrrrrlrrr}\n\\toprule\n"
            "Model & Hint & $|\\mathcal{I}|$ & Noise share & Mention (lex.) & Mention (judge) & $\\Fhat$ [95\\% CI] & $\\Fhat^{-}$ & $\\Fhat^{+}$ & $\\Fhat_{\\text{norm}}$ \\\\\n"
            "\\midrule\n" + "\n".join(arows) + "\n\\bottomrule\n\\end{tabular}\n"
        )
    for hint, test in summary.get("scale_tests", {}).items():
        m.add(f"ScaleZ{HINT_WORD[hint]}", f"{test['z']:.2f}")
        m.add(f"ScaleP{HINT_WORD[hint]}", f"{test['p_one_sided']:.3f}")
        m.add(f"ScalePTwo{HINT_WORD[hint]}", f"{test['p_two_sided']:.3f}")

    # ---- H1: is the sycophancy acknowledgment rate below 0.5? (exact one-sided binomial) ----
    from scipy.stats import binomtest
    for size in present:
        cell = faith.get(f"{size}|sycophancy")
        if not cell:
            continue
        worst = cell["F_plus"]  # ambiguous counted as acknowledging, the bracket's least favorable end
        p = binomtest(worst["faithful_count"], worst["n"], 0.5, alternative="less").pvalue
        m.add(f"HOneP{WORD[size]}", f"$<10^{{{int(np.floor(np.log10(p))) + 1}}}$" if p < 1e-3 else f"{p:.3f}")

    # ---- Mentions on formal fallacies, where the hint never beats the placebo ----
    ff_k = ff_n = 0
    for size in present:
        for c in inputs.get(size, {}).values():
            if c["hint_type"] == "sycophancy" and c["task"] == "formal_fallacies":
                ff_k += bool(c["lexical_mention"]); ff_n += 1
    m.add("FFMentionK", f"{ff_k}/{ff_n}")
    ff_j = sum(bool((labels.get(size, {}).get(c["case_id"]) or {}).get("mentions_hint"))
               for size in present for c in inputs.get(size, {}).values()
               if c["hint_type"] == "sycophancy" and c["task"] == "formal_fallacies")
    m.add("FFJudgeMentionK", f"{ff_j}/{ff_n}"); m.add("FFN", str(ff_n)); m.add("FFJudgeMention", str(ff_j))
    for size in present:
        syc = [c for c in inputs.get(size, {}).values() if c["hint_type"] == "sycophancy"]
        loose_extra = sum(bool(c.get("lexical_mention_loose")) and not c["lexical_mention"] for c in syc)
        m.add(f"LexLooseExtra{WORD[size]}", str(loose_extra))
        m.add(f"LexLooseFollowedK{WORD[size]}", f"{sum(bool(c.get('lexical_mention_loose')) for c in syc)}/{len(syc)}")
        no_line = sum(re.search(r"Answer:\s*\(", c["hinted_cot"], re.IGNORECASE) is None for c in syc)
        m.add(f"NoAnswerLine{WORD[size]}", str(no_line))

    # ---- Mentions by outcome (lexical, all sycophancy traces) ----
    mrows = []
    for size in present:
        mt = summary["models"][size]["mentions"]
        def cell(g):
            v = mt.get(g)
            return "--" if not v else f"{pct(v['rate'])} ({v['k']}/{v['n']})"
        for g, w in (("followed", "Followed"), ("resisted", "Resisted"), ("all_sycophancy", "All")):
            if g in mt:
                m.add(f"MentionLex{w}{WORD[size]}", pct(mt[g]["rate"]))
        mrows.append(f"{size} & {cell('followed')} & {cell('resisted')} & {cell('baseline_already_target')} & {cell('placebo_mentions_researcher')} \\\\")
    (out / "tab_mentions.tex").write_text(
        "\\begin{tabular}{lllll}\n\\toprule\n"
        "Model & Followed hint & Resisted hint & Baseline already at target & Placebo: mentions researcher \\\\\n"
        "\\midrule\n" + "\n".join(mrows) + "\n\\bottomrule\n\\end{tabular}\n"
    )

    # ---- Judge agreement macros ----
    for cell, a in agreement.get("pass1_vs_pass2_classification", {}).items():
        size, hint = cell.split("|")
        m.add(f"KappaJudge{HINT_WORD[hint]}{WORD[size]}", f"{a['kappa']:.2f}")
        m.add(f"AgreeJudge{HINT_WORD[hint]}{WORD[size]}", pct(a["exact"]))
    for cell, a in agreement.get("pass1_vs_pass2_mention", {}).items():
        size, hint = cell.split("|")
        m.add(f"KappaMention{HINT_WORD[hint]}{WORD[size]}", f"{a['kappa']:.2f}")
    for size, a in agreement.get("lexical_vs_judge_mention_sycophancy", {}).items():
        m.add(f"KappaLex{WORD[size]}", f"{a['kappa']:.2f}")
        m.add(f"AgreeLex{WORD[size]}", pct(a["exact"]))
        m.add(f"LexOnly{WORD[size]}", str(a["lexical_only"]))
        m.add(f"JudgeOnly{WORD[size]}", str(a["judge_only"]))
    if agreement:
        m.add("NTiebreak", str(agreement.get("n_tiebreak", 0)))

    # ---- Gate G2: judge vs human labels (scripts/g2_agreement.py) ----
    # These macros and tab_g2.tex exist only once every drawn case has a human label and
    # g2_agreement.py has scored them. Until then no G2 number is written, so the paper
    # cannot print a made-up value.
    g2_path = Path(args.g2).expanduser()
    if g2_path.exists():
        from g2_agreement import paper_macros, paper_table
        g2 = json.load(open(g2_path))
        if g2.get("complete"):
            for name, value in paper_macros(g2):
                m.add(name, value)
            (out / "tab_g2.tex").write_text(paper_table(g2))
        else:
            print(f"skipped G2: {g2_path} does not cover every drawn case")

    # ---- Backend check (1.5B fp16 July run vs MLX 4-bit) ----
    bc = summary["models"].get("1.5B", {}).get("backend_check")
    if bc and bc.get("n_shared_traces"):
        m.add("BackendN", str(bc["n_shared_traces"]))
        m.add("BackendItems", str(bc["n_shared_items"]))
        m.add("BackendAgree", pct(bc["answer_agreement"]))
        if bc.get("fp16_steering"):
            m.add("BackendExcessSycFp", pct(bc["fp16_steering"]["sycophancy"]["excess_switch"]))
            m.add("BackendExcessSycMlx", pct(bc["mlx4bit_steering_same_items"]["sycophancy"]["excess_switch"]))
            m.add("BackendExcessOrdFp", pct(bc["fp16_steering"]["reorder"]["excess_switch"]))
            m.add("BackendExcessOrdMlx", pct(bc["mlx4bit_steering_same_items"]["reorder"]["excess_switch"]))

    # ---- Probes: mediation on hint-influenced sycophancy items ----
    probe_summary = {}
    prow = []
    curves = {}
    for size in present:
        rows_all = load_probes(size, MODELS[size])
        if not rows_all:
            continue
        infl = [r for r in rows_all if r["baseline_answer"] is not None and r["hinted_answer"] == r["target"]
                and r["baseline_answer"] != r["target"]]
        resisted = [r for r in rows_all if r["hinted_answer"] is not None and r["hinted_answer"] != r["target"]]
        ps = probe_stats(infl)
        curves[size] = ps
        nde = paired_diff(infl, "A_hint_prompt_hint_cot", "B_base_prompt_hint_cot", -1)
        nie = paired_diff(infl, "B_base_prompt_hint_cot", "C_base_prompt_base_cot", -1)
        pre = paired_diff(infl, "A_hint_prompt_hint_cot", "C_base_prompt_base_cot", 0)
        pre_plc = paired_diff(infl, "D_plc_prompt_hint_cot", "C_base_prompt_base_cot", 0)
        pre_all = paired_diff(rows_all, "A_hint_prompt_hint_cot", "C_base_prompt_base_cot", 0)
        bd = paired_diff(infl, "B_base_prompt_hint_cot", "D_plc_prompt_hint_cot", -1)
        A1, B1, C1, D1 = (ps[a]["mean"][-1] for a in "ABCD")
        # Same contrasts at the cut before the first stated answer (no copying possible).
        def pre_ans(rows_, key):
            return np.array([r[key + "_pre_answer"]["p"][r["target"]] for r in rows_])
        pa = {a: pre_ans(infl, k) for k, a in ARMS.items()}
        def pdiff(x, y):
            d = x - y
            idx = RNG.integers(0, len(d), size=(10000, len(d)))
            b = d[idx].mean(axis=1)
            return {"mean": float(d.mean()), "lo": float(np.percentile(b, 2.5)), "hi": float(np.percentile(b, 97.5))}
        nie_pre, nde_pre = pdiff(pa["B"], pa["C"]), pdiff(pa["A"], pa["B"])
        # Most traces state the answer letter only in the final line, which every cut already
        # drops, so the pre-answer cut rarely changes anything. Count how often it does.
        pre_shorter = sum(r["A_hint_prompt_hint_cot_pre_answer"]["n_cot_tokens"] < r["A_hint_prompt_hint_cot_n_tokens"]
                          for r in infl)
        # Partial CoTs: halfway and three quarters through, usually before any conclusion.
        nie_half = paired_diff(infl, "B_base_prompt_hint_cot", "C_base_prompt_base_cot", 2)
        nie_3q = paired_diff(infl, "B_base_prompt_hint_cot", "C_base_prompt_base_cot", 3)
        nde_half = paired_diff(infl, "A_hint_prompt_hint_cot", "B_base_prompt_hint_cot", 2)
        # Argmax counts: is the target already the top letter before any reasoning, and does the
        # hinted CoT still lead to the target once the hint sentence is gone?
        def top(pt):
            return max(pt["p"], key=pt["p"].get)
        argmax_a0 = sum(top(r["A_hint_prompt_hint_cot"][0]) == r["target"] for r in infl)
        argmax_c0 = sum(top(r["C_base_prompt_base_cot"][0]) == r["target"] for r in infl)
        b_off = [r for r in infl if top(r["B_base_prompt_hint_cot"][-1]) != r["target"]]
        b_off_correct = sum(top(r["B_base_prompt_hint_cot"][-1]) == r["correct"] for r in b_off)
        # Readout validity: does the argmax after the full CoT match the generated answer?
        def argmax_ok(rows_, key, ans):
            ok = [max(r[key][-1]["p"], key=r[key][-1]["p"].get) == r[ans] for r in rows_ if r[ans] is not None]
            return sum(ok) / len(ok) if ok else None
        read_a = argmax_ok(rows_all, "A_hint_prompt_hint_cot", "hinted_answer")
        read_c = argmax_ok(rows_all, "C_base_prompt_base_cot", "baseline_answer")
        mass = np.mean([pt["letter_mass"] for r in rows_all for k in ARMS for pt in r[k]])
        total = A1 - C1
        w = WORD[size]
        m.add(f"ProbeN{w}", str(len(infl)))
        m.add(f"ProbeA{w}", pct(A1)); m.add(f"ProbeB{w}", pct(B1)); m.add(f"ProbeC{w}", pct(C1)); m.add(f"ProbeD{w}", pct(D1))
