def make_probe_figure(curves: dict, path: Path) -> None:
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    plt.rcParams.update(FIG_RC)
    colors = {"A": "#2a78d6", "B": "#eb6834", "D": "#1baf7a", "C": "#52514e"}
    names = {"A": "A: hint prompt + hinted CoT", "B": "B: no hint + hinted CoT",
             "D": "D: placebo + hinted CoT", "C": "C: no hint + baseline CoT"}
    styles = {"A": "-", "B": "-", "D": "--", "C": ":"}
    sizes = [s for s in SIZES if s in curves]
    fig, axes = plt.subplots(1, len(sizes), figsize=(2.3 * len(sizes), 2.0), sharey=True)
    axes = np.atleast_1d(axes)
    x = [0, 25, 50, 75, 100]
    for ax, size in zip(axes, sizes):
        for arm in ("A", "B", "D", "C"):
            c = curves[size][arm]
            ax.plot(x, [100 * v for v in c["mean"]], styles[arm], color=colors[arm], lw=1.6, marker="o", ms=3,
                    label=names[arm])
            ax.fill_between(x, [100 * v for v in c["lo"]], [100 * v for v in c["hi"]], color=colors[arm], alpha=0.12, lw=0)
        ax.set_title(f"Qwen2.5-{size}-Instruct", fontsize=8)
        ax.set_xlabel("CoT shown (% of tokens)")
        ax.set_xticks(x)
        ax.set_ylim(0, 100)
        ax.grid(axis="y", color="#e6e5e0", lw=0.6)
    axes[0].set_ylabel("P(hint target), %")
    handles, labels_ = axes[0].get_legend_handles_labels()
    fig.legend(handles, labels_, loc="lower center", ncol=4, frameon=False, fontsize=8, bbox_to_anchor=(0.5, -0.04))
    fig.tight_layout(rect=(0, 0.1, 1, 1))
    fig.savefig(path, bbox_inches="tight")
    plt.close(fig)


def make_steering_figure(summary: dict, sizes: list[str], path: Path) -> None:
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    plt.rcParams.update(FIG_RC)
    colors = {"sycophancy": "#2a78d6", "reorder": "#eb6834", "placebo": "#8a8984"}
    fig, ax = plt.subplots(figsize=(3.6, 2.4))
    width = 0.26
    max_v = 0.0
    for i, size in enumerate(sizes):
        st = summary["models"][size]["steering_answer_v2"]
        vals = [("sycophancy", st["sycophancy"]["switch_to_target"]),
                ("reorder", st["reorder"]["switch_to_target"]),
                ("placebo", st["sycophancy"]["placebo_switch_to_dummy"])]
        for j, (name, v) in enumerate(vals):
            max_v = max(max_v, v)
            ax.bar(i + (j - 1) * width, 100 * v, width - 0.03, color=colors[name],
                   label={"sycophancy": "sycophancy hint", "reorder": "reordering hint",
                          "placebo": "placebo (dummy target)"}[name] if i == 0 else None)
            ax.text(i + (j - 1) * width, 100 * v + 1, f"{100 * v:.0f}", ha="center", va="bottom", fontsize=8, color="#333333")
    ax.set_xticks(range(len(sizes)))
    ax.set_xticklabels(sizes)
    ax.set_xlabel("Qwen2.5 Instruct model size")
    ax.set_ylabel("Switch to target, %")
    ax.grid(axis="y", color="#e6e5e0", lw=0.6)
    ax.set_axisbelow(True)
    ax.set_ylim(0, 100 * max_v * 1.12 + 2)
    ax.legend(frameon=False, fontsize=8, loc="lower center", ncol=2, bbox_to_anchor=(0.5, 1.0))
    fig.tight_layout()
    fig.savefig(path, bbox_inches="tight")
    plt.close(fig)


